const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('src/shared/window-appearance.js', 'utf8');
const values = new Map(), root = { dataset: {}, style: { setProperty: (key, value) => values.set(key, value) } };
const context = { document: { documentElement: root }, location: { search: '?theme=light&accent=%23eec84a' }, URLSearchParams };
vm.createContext(context); vm.runInContext(source, context);
assert.equal(root.dataset.theme, 'light');
assert.equal(values.get('--accent'), '#eec84a');
assert.equal(values.get('--accent-ink'), '#171220');
assert.notEqual(values.get('--accent-fg'), '#eec84a', 'pale accent text must remain readable on a light surface');
context.NoctuneWindowAppearance.apply({ theme: 'dark', accent: '#123456' });
assert.equal(root.dataset.theme, 'dark');
assert.equal(values.get('--accent'), '#123456');
assert.equal(values.get('--accent-ink'), '#ffffff');
assert.notEqual(values.get('--accent-fg'), '#123456', 'dark accent text must remain readable on a dark surface');
context.NoctuneWindowAppearance.apply({ theme: 'invalid', accent: 'url(https://example.com)' });
assert.equal(root.dataset.theme, 'dark');
assert.equal(values.get('--accent'), '#ac91ee');
console.log('PASS: window theme/accent inheritance, readable accent text, contrasting button labels and invalid input fallback.');
