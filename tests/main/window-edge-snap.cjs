const assert = require('node:assert/strict');
const { createEdgeSnap } = require('../../src/main/window-edge-snap');
const snap = createEdgeSnap();
const area = { x: 0, y: 32, width: 1920, height: 1008 };
const bounds = { x: 500, y: 300, width: 440, height: 96 };
const move = (x, y = 300, workArea = area) => snap.move({ ...bounds, x, y }, workArea);
assert.equal(move(13).x, 13);
assert.equal(move(12).x, 0);
for (const x of [13, 11, 15, 20, -7, 21, 14]) assert.equal(move(x).x, 0, 'small pointer movements cannot detach a captured edge');
assert.equal(move(22).x, 22, 'dragging further deliberately releases the edge');
assert.equal(move(16).x, 16, 'release does not immediately snap back');
assert.equal(move(10).x, 0);
snap.reset();
const right = area.width - bounds.width, bottom = area.y + area.height - bounds.height;
assert.deepEqual(move(right - 6, bottom - 10), { ...bounds, x: right, y: bottom });
assert.deepEqual(move(right - 20, bottom - 21), { ...bounds, x: right, y: bottom });
assert.deepEqual(move(right - 22, bottom - 22), { ...bounds, x: right - 22, y: bottom - 22 });
snap.reset(); assert.equal(move(500, 42).y, 32, 'top taskbar work-area offset is respected');
const leftMonitor = { x: -1600, y: -200, width: 1600, height: 900 };
assert.equal(move(-1590, 100, leftMonitor).x, -1600, 'negative monitor coordinates work');
const secondMonitor = { x: 1920, y: 0, width: 1280, height: 1024 };
assert.equal(move(1955, 100, secondMonitor).x, 1955, 'crossing monitors discards the previous attachment');
assert.equal(move(1930, 100, secondMonitor).x, 1920);
snap.reset(); assert.equal(move(1955, 100, secondMonitor).x, 1955, 'disabled/reset snapping releases attachments');
console.log('PASS: edge capture, hysteresis against jitter, intentional release, corner attachment, taskbar work areas, negative coordinates and monitor changes.');
