const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const p = require('../../src/main/addons/package');
const { createAddonStore } = require('../../src/main/addons/store');
const clone = value => JSON.parse(JSON.stringify(value));
(async () => {
    const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'noctune-addon-store-'));
    try {
        const original = await p.packDirectory('addons/examples/track-info');
        original.manifest.update = { url: 'https://publisher.example/release.json', channel: 'stable' };
        const key = crypto.generateKeyPairSync('ed25519').privateKey.export({ format: 'pem', type: 'pkcs8' });
        const pkg = p.sign(original, key);
        const downloads = new Map();
        const options = { directory, appVersion: '1.4.0', fetchText: async url => { if (!downloads.has(url)) throw new Error('Offline'); return downloads.get(url); } };
        const store = createAddonStore(options);
        const candidate = await store.preparePackage(pkg);
        assert.equal((await store.list()).length, 0, 'preview never installs');
        await store.confirm(candidate.ticket);
        assert.equal((await store.list())[0].enabled, false, 'new extensions start disabled');
        assert.equal((await store.runtime()).length, 0);
        await store.setEnabled(pkg.manifest.id, true);
        let runtime = (await store.runtime())[0];
        await store.invoke(pkg.manifest.id, runtime.digest, 'storage.set', { key: 'count', value: 7 });
        assert.equal(await store.invoke(pkg.manifest.id, runtime.digest, 'storage.get', { key: 'count' }), 7);
        await assert.rejects(store.invoke(pkg.manifest.id, runtime.digest, 'storage.set', { key: '__proto__', value: {} }));
        await assert.rejects(store.invoke(pkg.manifest.id, runtime.digest, 'storage.set', { key: 'huge', value: 'x'.repeat(128 * 1024) }));
        await assert.rejects(store.request(pkg.manifest.id, runtime.digest, 'https://publisher.example/'), /разрешения/);
        const updatedPackage = clone(original); updatedPackage.manifest.version = '1.1.0'; updatedPackage.manifest.revision = 2;
        updatedPackage.manifest.permissions.push('network.request'); updatedPackage.manifest.network = { origins: ['https://publisher.example'] };
        const signed2 = p.sign(updatedPackage, key), source2 = p.canonical(signed2);
        const release = p.sign({ format: 'noctune-addon-release', formatVersion: 1, id: original.manifest.id, version: '1.1.0', revision: 2, channel: 'stable', packageUrl: 'https://publisher.example/updatedPackage.noctaddon', sha256: crypto.createHash('sha256').update(source2).digest('hex') }, key);
        downloads.set(original.manifest.update.url, p.canonical(release)); downloads.set(release.packageUrl, source2);
        const update = await store.checkUpdate(original.manifest.id);
        assert.deepEqual(update.addedPermissions, ['network.request']);
        assert.deepEqual(update.addedOrigins, ['https://publisher.example']);
        assert.equal((await store.list())[0].version, '1.0.0', 'update check does not install');
        await store.confirm(update.ticket);
        assert.equal((await store.list())[0].version, '1.1.0');
        assert.equal((await store.list())[0].enabled, true);
        await assert.rejects(store.invoke(original.manifest.id, runtime.digest, 'storage.get', { key: 'count' }), /обновлено/);
        runtime = (await store.runtime())[0];
        assert.equal(await store.invoke(original.manifest.id, runtime.digest, 'storage.get', { key: 'count' }), 7);
        await assert.rejects(store.confirm(update.ticket), /истекло/);
        const reloaded = createAddonStore(options);
        assert.equal((await reloaded.list())[0].version, '1.1.0', 'registry survives restart');
        await reloaded.rollback(original.manifest.id);
        assert.equal((await reloaded.list())[0].version, '1.0.0');
        assert.equal((await reloaded.checkUpdate(original.manifest.id)).state, 'current', 'rollback does not reoffer rejected revision');
        await assert.rejects(reloaded.preparePackage(signed2), /ревизия/);
        const otherKey = crypto.generateKeyPairSync('ed25519').privateKey.export({ format: 'pem', type: 'pkcs8' });
        const nextPackage = clone(updatedPackage); nextPackage.manifest.version = '1.2.0'; nextPackage.manifest.revision = 3;
        await assert.rejects(reloaded.preparePackage(p.sign(nextPackage, otherKey)), /Издатель/);
        const incompatible = clone(nextPackage); incompatible.manifest.minNoctuneVersion = '9.0.0';
        await assert.rejects(reloaded.preparePackage(p.sign(incompatible, key)), /несовместимо/);
        const valid3 = await reloaded.preparePackage(p.sign(nextPackage, key));
        const concurrent3 = await reloaded.preparePackage(p.sign(nextPackage, key));
        await reloaded.confirm(valid3.ticket);
        await assert.rejects(reloaded.confirm(concurrent3.ticket), /изменилось/);
        const badRelease = clone(release); badRelease.revision = 4;
        downloads.set(original.manifest.update.url, JSON.stringify(badRelease));
        await assert.rejects(reloaded.checkUpdate(original.manifest.id), /подпись/i);
        const release4 = { ...p.sign({ ...release, revision: 4, version: '1.3.0' }, key) };
        downloads.set(original.manifest.update.url, p.canonical(release4));
        downloads.set(release.packageUrl, source2 + '\nchanged');
        await assert.rejects(reloaded.checkUpdate(original.manifest.id), /сумма/);
        downloads.set(original.manifest.update.url, p.canonical(p.sign(release4, otherKey)));
        await assert.rejects(reloaded.checkUpdate(original.manifest.id), /другому издателю/);
        assert.equal((await reloaded.list())[0].version, '1.2.0', 'failed update leaves active version intact');
        const second = clone(nextPackage); second.manifest.id = 'second-addon';
        const secondPreview = await reloaded.preparePackage(p.sign(second, key));
        await reloaded.confirm(secondPreview.ticket); await reloaded.setEnabled(second.manifest.id, true);
        const secondRuntime = (await reloaded.runtime()).find(item => item.manifest.id === second.manifest.id);
        assert.equal(await reloaded.invoke(second.manifest.id, secondRuntime.digest, 'storage.get', { key: 'count' }), null, 'storage is isolated by addon ID');
        await reloaded.remove(second.manifest.id);
        await reloaded.setEnabled(original.manifest.id, false);
        assert.equal((await reloaded.runtime()).length, 0);
        await reloaded.remove(original.manifest.id);
        assert.equal((await reloaded.list()).length, 0);
        await assert.rejects(fs.stat(path.join(directory, 'storage', original.manifest.id + '.json')), { code: 'ENOENT' });
        const unsigned = await reloaded.preparePackage(await p.packDirectory('addons/examples/track-info'));
        reloaded.discard(unsigned.ticket); await assert.rejects(reloaded.confirm(unsigned.ticket));
        downloads.set('https://publisher.example/unsigned.noctaddon', p.canonical(await p.packDirectory('addons/examples/track-info')));
        await assert.rejects(reloaded.prepareUrl('https://publisher.example/unsigned.noctaddon'), /подпис/);
        console.log('PASS: addon preview/consent, persistence, scoped storage, signed updates, permission escalation, identity pinning, atomic activation, rollback and stale-request rejection.');
    } finally { await fs.rm(directory, { recursive: true, force: true }); }
})().catch(error => { console.error(error); process.exitCode = 1; });
